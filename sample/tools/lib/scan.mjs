for (const [c, rows] of Object.entries(GLYPHS)) {
	if (rows.length !== 7 || rows.some((r) => r.length !== 5))
		throw new Error(`glyph ${c} is not 5 by 7`);
}

export const WIDTH = 1700;
export const HEIGHT = 2200;
const SCALE = 4;
const ADVANCE = 6 * SCALE;
const LINE = 11 * SCALE;
const MARGIN = 100;

export const scanChars = new Set(Object.keys(GLYPHS));

// Rows of packed bits, 1 = white, as DeviceGray with BitsPerComponent 1.
export function render(lines) {
	const rowBytes = Math.ceil(WIDTH / 8);
	const bytes = new Uint8Array(rowBytes * HEIGHT).fill(0xff);
	const ink = (x, y) => (bytes[y * rowBytes + (x >> 3)] &= ~(0x80 >> (x & 7)));
	if (MARGIN * 2 + lines.length * LINE > HEIGHT)
		throw new Error(`${lines.length} lines do not fit on a scanned page`);
	lines.forEach((line, row) => {
		const chars = [...line];
		if (MARGIN * 2 + chars.length * ADVANCE > WIDTH)
			throw new Error(`line too long for a scanned page: ${line}`);
		chars.forEach((c, col) => {
			const bits = GLYPHS[c]?.join('');
			if (!bits) throw new Error(`no scan glyph for ${JSON.stringify(c)} in: ${line}`);
			for (let i = 0; i < 35; i++) {
				if (bits[i] !== '#') continue;
				const x0 = MARGIN + col * ADVANCE + (i % 5) * SCALE;
				const y0 = MARGIN + row * LINE + Math.floor(i / 5) * SCALE;
				for (let dy = 0; dy < SCALE; dy++) for (let dx = 0; dx < SCALE; dx++) ink(x0 + dx, y0 + dy);
			}
		});
	});
	return bytes;
}

// PDF RunLengthDecode encoding.
export function runLength(data) {
	const out = [];
	let i = 0;
	while (i < data.length) {
		let run = 1;
		while (i + run < data.length && run < 128 && data[i + run] === data[i]) run++;
		if (run > 1) {
			out.push(257 - run, data[i]);
			i += run;
			continue;
		}
		let end = i + 1;
		while (
			end < data.length &&
			end - i < 128 &&
			!(end + 1 < data.length && data[end] === data[end + 1])
		)
			end++;
		out.push(end - i - 1, ...data.subarray(i, end));
		i = end;
	}
	out.push(128);
	return Uint8Array.from(out);
}
